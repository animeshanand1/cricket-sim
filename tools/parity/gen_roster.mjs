// Generates src/engine/roster_data.cpp from the JS roster (the single source of truth).
// Usage: node tools/parity/gen_roster.mjs > src/engine/roster_data.cpp
import { ROSTER } from '../../../t20-coach/src/engine/roster.js';

const str = (s) => (s == null ? '""' : JSON.stringify(s));
const optType = (t) => (t == null ? 'std::nullopt' : `BowlType::${t}`);

const out = [];
out.push('// GENERATED by tools/parity/gen_roster.mjs from t20-coach/src/engine/roster.js. Do not edit.');
out.push('#include "engine/roster.hpp"');
out.push('');
out.push('namespace t20 {');
out.push('');
out.push('const std::vector<RosterTeam>& ROSTER() {');
out.push('  static const std::vector<RosterTeam> roster = {');
for (const t of ROSTER) {
  out.push(`    {{${str(t.id)}, Captain::${t.captain}, ${str(t.personality)}, ${str(t.name)}, ${str(t.city)}, ${str(t.color)}, ${str(t.ground)}, Pitch::${t.pitch}},`);
  out.push('     {');
  for (const r of t.players) {
    const [name, role, hand, bowlType, bat, power, bowl, field, age, os, batStyle, bowlStyle] = r;
    out.push(`       {${str(name)}, Role::${role}, Hand::${hand}, ${optType(bowlType)}, ${bat}, ${power}, ${bowl}, ${field}, ${age}, ${os ? 'true' : 'false'}, ${str(batStyle)}, ${str(bowlStyle)}},`);
  }
  out.push('     }},');
}
out.push('  };');
out.push('  return roster;');
out.push('}');
out.push('');
out.push('}  // namespace t20');
console.log(out.join('\n'));
